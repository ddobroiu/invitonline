import { chromium } from '@playwright/test'
import fs from 'node:fs'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
fs.mkdirSync('shots/redesign', { recursive: true })
await page.goto('http://localhost:3015', { waitUntil: 'networkidle', timeout: 120000 })
await page.getByRole('button', { name: 'Refuză', exact: true }).click()
await page.screenshot({ path: 'shots/redesign/home-desktop.png' })
await page.setViewportSize({ width: 360, height: 800 })
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 360)
await page.screenshot({ path: 'shots/redesign/home-mobile.png' })
await page.getByRole('button', { name: 'Deschide meniul' }).click()
assert.equal(await page.getByRole('navigation', { name: 'Navigare mobilă' }).isVisible(), true)
await page.keyboard.press('Escape')
await page.setViewportSize({ width: 1440, height: 1000 })
console.log('HOME', await page.title())
await page.goto('http://localhost:3015/demo', { waitUntil: 'networkidle', timeout: 120000 })
await page.locator('iframe').first().waitFor()
await page.waitForTimeout(3000)
await page.screenshot({ path: 'shots/redesign/gallery-desktop.png' })
assert.equal(await page.locator('article').count(), 21)
await page.locator('article').first().scrollIntoViewIfNeeded()
await page.screenshot({ path: 'shots/redesign/gallery-cards.png' })
console.log('MODELS', await page.locator('article').count())
console.log('FRAME', await page.frames()[1].evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth, text: document.body.innerText.slice(0,100), style: getComputedStyle(document.querySelector('h1')).fontSize })))
await page.getByRole('button', { name: 'Botez', exact: true }).click()
assert.equal(await page.locator('article').count(), 6)
console.log('FILTER', await page.locator('article').count())
await page.setViewportSize({ width: 390, height: 844 })
await page.screenshot({ path: 'shots/redesign/gallery-mobile.png' })
console.log('MOBILE', await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth })))
await page.goto('http://localhost:3015/create?template=modern', { waitUntil: 'networkidle', timeout: 120000 })
await page.setViewportSize({ width: 1440, height: 1000 })
await page.waitForTimeout(2000)
await page.screenshot({ path: 'shots/redesign/editor-desktop.png' })
console.log('EDITOR', await page.locator('iframe').count())
await page.getByRole('button', { name: 'Detalii', exact: true }).click()
await page.locator('#f-brideName').fill('Alexandra Maria')
await page.locator('#f-groomName').fill('Constantin Alexandru')
await page.waitForTimeout(400)
assert.ok((await page.frames()[1].locator('h1').innerText()).includes('Alexandra Maria'))
console.log('LIVE EDITOR UPDATE: passed')
await page.goto('http://localhost:3015/demo', { waitUntil: 'networkidle' })
for (const article of await page.locator('article').all()) {
    await article.scrollIntoViewIfNeeded()
    const iframe = article.locator('iframe')
    await iframe.waitFor()
    const frame = await (await iframe.elementHandle()).contentFrame()
    await frame.locator('body > div > div').first().waitFor()
    await frame.waitForFunction(() => getComputedStyle(document.body).margin === '0px')
    await frame.waitForFunction(() => [...document.querySelectorAll('link[rel="stylesheet"]')].every(link => link.sheet))
    const size = await frame.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }))
    assert.ok(size.scroll <= size.width + 1, await article.locator('h2').innerText() + ' overflows')
}
console.log('ALL 21 FRAMES: no horizontal overflow')
console.log('ERRORS', errors)
assert.equal(errors.length, 0)
await browser.close()
